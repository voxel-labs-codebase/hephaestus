//! User actions: every menu item, toolbar button and shortcut maps to one [`Action`], so the
//! same operation behaves identically wherever it is invoked.

use hephaestus_commands::{AlignMode, Axis};

use crate::documents::DocKey;
use crate::workspace::PanelId;

#[derive(Clone, Debug, PartialEq)]
pub enum Action {
    NewProject,
    OpenProject,
    OpenRecent(std::path::PathBuf),
    OpenDemo,
    Save,
    SaveAs,
    Exit,
    Undo,
    Redo,
    Cut,
    Copy,
    Paste,
    Delete,
    SelectAll,
    ClearSelection,
    Rotate,
    MirrorX,
    FlipSide,
    Fit,
    FitDocument,
    FitSelection,
    ZoomIn,
    ZoomOut,
    ToggleUnits,
    CycleGrid,
    ToggleGridVisible,
    Compile,
    RunErc,
    RunDrc,
    UpdatePcb,
    AddSheet,
    RemoveSheet,
    OpenDoc(DocKey),
    SchTool(SchToolKind),
    PcbTool(PcbToolKind),
    NextLayer,
    PrevLayer,
    ToggleSingleLayer,
    LayerStack,
    DesignRules,
    ExportGerber,
    ExportDrill,
    ExportBom,
    ExportPickPlace,
    ExportAll,
    Align(AlignMode),
    Distribute(Axis),
    Lock(bool),
    CrossProbe,
    ClearHighlight,
    TogglePanel(PanelId),
    ResetLayout,
    Preferences,
    About,
    ShortcutHelp,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum SchToolKind {
    Select,
    Part,
    Wire,
    NetLabel,
    Vcc,
    Gnd,
    Port,
    Junction,
    NoErc,
    Text,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum PcbToolKind {
    Select,
    Route,
    Track,
    Via,
    Zone,
    Keepout,
    BoardShape,
    Measure,
}

/// Shortcut legend shown in menus and the Help › Shortcuts window.
pub fn shortcut(action: &Action) -> &'static str {
    match action {
        Action::NewProject => "Ctrl+N",
        Action::OpenProject => "Ctrl+O",
        Action::Save => "Ctrl+S",
        Action::Undo => "Ctrl+Z",
        Action::Redo => "Ctrl+Y",
        Action::Cut => "Ctrl+X",
        Action::Copy => "Ctrl+C",
        Action::Paste => "Ctrl+V",
        Action::Delete => "Del",
        Action::SelectAll => "Ctrl+A",
        Action::ClearSelection => "X, A",
        Action::Rotate => "Space",
        Action::MirrorX => "X",
        Action::FlipSide => "L",
        Action::Fit => "Ctrl+PgDn",
        Action::FitDocument => "V, D",
        Action::FitSelection => "Z, S",
        Action::ZoomIn => "PgUp",
        Action::ZoomOut => "PgDn",
        Action::ToggleUnits => "Q",
        Action::CycleGrid => "G",
        Action::RunErc => "D, E",
        Action::RunDrc => "T, D",
        Action::Compile => "C, C",
        Action::UpdatePcb => "D, U",
        Action::SchTool(SchToolKind::Wire) => "P, W",
        Action::SchTool(SchToolKind::NetLabel) => "P, N",
        Action::SchTool(SchToolKind::Vcc) => "P, O",
        Action::SchTool(SchToolKind::Gnd) => "P, G",
        Action::SchTool(SchToolKind::Port) => "P, R",
        Action::SchTool(SchToolKind::Junction) => "P, J",
        Action::SchTool(SchToolKind::NoErc) => "P, V",
        Action::SchTool(SchToolKind::Text) => "P, T",
        Action::SchTool(SchToolKind::Part) => "P, P",
        Action::PcbTool(PcbToolKind::Route) => "Ctrl+W",
        Action::PcbTool(PcbToolKind::Track) => "P, L",
        Action::PcbTool(PcbToolKind::Via) => "P, V",
        Action::PcbTool(PcbToolKind::Zone) => "P, G",
        Action::PcbTool(PcbToolKind::Keepout) => "P, K",
        Action::PcbTool(PcbToolKind::Measure) => "Ctrl+M",
        Action::NextLayer => "Num *",
        Action::PrevLayer => "Num -",
        Action::ToggleSingleLayer => "Shift+S",
        Action::Preferences => "T, P",
        Action::ShortcutHelp => "F1",
        Action::ClearHighlight => "Shift+C",
        _ => "",
    }
}
